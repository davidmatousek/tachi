#[test]
fn extract_prompt_scaffold_reads_the_risk_funnel_prompt_block() {
    let repo_root = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("..");

    let scaffold = extract_prompt_scaffold("risk-funnel", Some(&repo_root));

    assert!(scaffold.found);
    assert!(scaffold
        .preamble
        .contains("DATA CONTENT (render this as visible text):"));
    assert!(scaffold.preamble.contains("STYLING DIRECTIVES"));
    assert!(scaffold.postamble.contains("FOOTER"));
    assert!(scaffold
        .postamble
        .contains("Generated by Tachi Threat Modeling Framework"));
    assert!(!scaffold.preamble.is_empty());
    assert!(!scaffold.postamble.is_empty());
}

#[test]
fn extract_prompt_scaffold_returns_empty_when_template_is_unknown() {
    let repo_root = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("..");

    let scaffold = extract_prompt_scaffold("not-a-template", Some(&repo_root));

    assert_eq!(scaffold.found, false);
    assert_eq!(scaffold.preamble, "");
    assert_eq!(scaffold.postamble, "");
}

#[test]
fn compute_metadata_builds_expected_infographic_fields() {
    let threats_content = r#"
# Threat Model

### 3.1 Example Agent

### 4.2 Example Agent
"#;
    let frontmatter = BTreeMap::from([
        (String::from("date"), String::from("2026-06-05")),
        (String::from("schema_version"), String::from("1.4")),
    ]);
    let severity = SeverityCounts {
        critical: 2,
        high: 3,
        medium: 4,
        low: 5,
        note: 6,
        total: 20,
    };
    let scope_components = vec![
        ScopeComponent {
            name: String::from("API"),
            kind: String::from("Process"),
            description: String::from(""),
        },
        ScopeComponent {
            name: String::from("DB"),
            kind: String::from("Data Store"),
            description: String::from(""),
        },
    ];

    let metadata = compute_metadata(
        threats_content,
        &frontmatter,
        1,
        &severity,
        &scope_components,
        "Acme Project",
    );

    assert_eq!(metadata.project_name, "Acme Project");
    assert_eq!(metadata.scan_date, "2026-06-05");
    assert_eq!(metadata.tier, 1);
    assert_eq!(metadata.data_source_type, "compensating-controls");
    assert_eq!(metadata.total_findings, 20);
    assert_eq!(metadata.note_count, 6);
    assert_eq!(metadata.agent_count, 2);
    assert_eq!(
        metadata.risk_posture,
        "Residual risk — 2 Critical and 3 High findings across 2 components"
    );
    assert_eq!(metadata.schema_version, "1.4");
}

