#[test]
fn validate_infographic_reports_all_consistency_errors() {
    let data = InfographicValidationData {
        metadata: InfographicMetadata {
            total_findings: 6,
            note_count: 1,
            ..Default::default()
        },
        severity_distribution: vec![
            SeverityDistributionEntry {
                label: String::from("Critical"),
                count: 1,
            },
            SeverityDistributionEntry {
                label: String::from("High"),
                count: 1,
            },
        ],
        heat_map: vec![HeatMapRow {
            component: String::from("API"),
            critical: 1,
            high: 1,
            medium: 0,
            low: 1,
            total: 4,
        }],
        top_findings: vec![TopFinding {
            id: String::from("S-9"),
        }],
        findings_ids: BTreeSet::from([String::from("S-1")]),
    };

    let errors = validate_infographic(&data);

    assert_eq!(errors.len(), 3);
    assert!(errors
        .iter()
        .any(|error| error.contains("Severity sum mismatch")));
    assert!(errors
        .iter()
        .any(|error| error.contains("Top finding ID S-9 not found")));
    assert!(errors
        .iter()
        .any(|error| error.contains("Heat map row 'API'")));
}

#[test]
fn compute_component_risk_weights_sorts_by_score_then_component_name() {
    let heat_map = vec![
        HeatMapRow {
            component: String::from("Zulu"),
            critical: 1,
            high: 1,
            medium: 0,
            low: 0,
            total: 2,
        },
        HeatMapRow {
            component: String::from("Alpha"),
            critical: 0,
            high: 2,
            medium: 0,
            low: 0,
            total: 2,
        },
        HeatMapRow {
            component: String::from("Bravo"),
            critical: 0,
            high: 0,
            medium: 0,
            low: 0,
            total: 0,
        },
    ];

    let weights = tachi_core::infographic::compute_component_risk_weights(&heat_map);

    assert_eq!(weights.len(), 3);
    assert_eq!(
        weights[0],
        ComponentRiskWeight {
            component: String::from("Zulu"),
            weight: String::from("high"),
            score: 3.5,
            annotation: String::from("1 Critical + 1 High findings"),
        }
    );
    assert_eq!(
        weights[1],
        ComponentRiskWeight {
            component: String::from("Alpha"),
            weight: String::from("high"),
            score: 3.0,
            annotation: String::from("2 High findings"),
        }
    );
    assert_eq!(
        weights[2],
        ComponentRiskWeight {
            component: String::from("Bravo"),
            weight: String::from("low"),
            score: 0.0,
            annotation: String::from("No findings"),
        }
    );
}

#[test]
fn compute_most_exposed_layer_prefers_count_then_severity_then_layer_id() {
    let layer_distribution = vec![
        MaestroLayerDistributionEntry {
            layer_id: String::from("L2"),
            layer_name: String::from("Layer 2"),
            finding_count: 5,
            highest_severity: String::from("High"),
        },
        MaestroLayerDistributionEntry {
            layer_id: String::from("L1"),
            layer_name: String::from("Layer 1"),
            finding_count: 5,
            highest_severity: String::from("Critical"),
        },
        MaestroLayerDistributionEntry {
            layer_id: String::from("L3"),
            layer_name: String::from("Layer 3"),
            finding_count: 4,
            highest_severity: String::from("Critical"),
        },
    ];

    assert_eq!(
        compute_most_exposed_layer(&layer_distribution),
        "L1 — Layer 1"
    );
}

